/**
 * Autostart + crash recovery for the LAN remote host (local-only feature).
 *
 * The desktop's own auto-launch (`autoLauncher.ts`, the `auto-launch` package)
 * can only start Chatbox with no arguments, so it cannot bring up `--serve`.
 * Instead of fighting it we register a single Windows scheduled task that:
 *
 *   - runs at logon (so the remote host is up right after logging in), and
 *   - repeats every 5 minutes (so a main-process crash heals itself).
 *
 * The task runs `serve-guard.ps1` (written next to the log) hidden. The guard
 * starts `Chatbox.exe --serve` only when no Chatbox process is running at all -
 * if the user opened the normal window, we never fight it for the
 * single-instance lock.
 *
 * Everything is per-user (HKCU task store), needs no admin rights, and is
 * reversible with `removeServeAutostart()`.
 */
import { execFile } from 'node:child_process'
import fs from 'node:fs'
import path from 'node:path'
import { app } from 'electron'
import log from 'electron-log/main'

const TASK_NAME = 'ChatboxLANRemote'
const GUARD_FILE = 'serve-guard.ps1'

export interface ServeAutostartOptions {
  /** Port the guard should start the server on. */
  port: number
}

function psQuote(value: string): string {
  return `'${value.replace(/'/g, "''")}'`
}

function runPowerShell(args: string[], timeoutMs = 20_000): Promise<{ code: number; stdout: string; stderr: string }> {
  return new Promise((resolve) => {
    execFile(
      'powershell.exe',
      ['-NoProfile', '-NonInteractive', '-ExecutionPolicy', 'Bypass', ...args],
      { windowsHide: true, timeout: timeoutMs },
      (error, stdout, stderr) => {
        const code = error && typeof (error as { code?: number }).code === 'number' ? (error as { code: number }).code : 0
        resolve({ code: error ? code : 0, stdout: String(stdout ?? ''), stderr: String(stderr ?? '') })
      }
    )
  })
}

function guardPath(): string {
  return path.join(app.getPath('userData'), GUARD_FILE)
}

function buildGuardScript(port: number): string {
  const exe = process.execPath
  return `# Chatbox LAN remote host guard (generated by Chatbox). Safe to delete.
# Starts "Chatbox.exe --serve" at logon and restarts it after a crash.
$ErrorActionPreference = 'SilentlyContinue'
$exe = ${psQuote(exe)}
$arguments = @('--serve', '--port=${port}')
$all = @(Get-CimInstance Win32_Process -Filter "Name='Chatbox.exe'")
if ($all.Count -eq 0) {
  Start-Process -FilePath $exe -ArgumentList $arguments -WindowStyle Hidden
  exit 0
}
# Any running instance (serve or normal) already owns the single-instance lock.
exit 0
`
}

/**
 * Idempotent: writes the guard script and (re)registers the task. Runs hidden,
 * so on a machine someone is gaming on nothing flashes on screen.
 */
export async function installServeAutostart(options: ServeAutostartOptions): Promise<boolean> {
  if (process.platform !== 'win32') {
    log.warn('[remote-host] autostart: only implemented for Windows')
    return false
  }
  const script = guardPath()
  try {
    fs.writeFileSync(script, buildGuardScript(options.port), 'utf8')
  } catch (error) {
    log.error('[remote-host] autostart: cannot write guard script', error)
    return false
  }

  const register = `
$ErrorActionPreference = 'Stop'
# $env:USERNAME alone does not map back to a SID for -AtLogOn (it needs DOMAIN\\user).
$who = [System.Security.Principal.WindowsIdentity]::GetCurrent().Name
$action = New-ScheduledTaskAction -Execute 'powershell.exe' -Argument ${psQuote(
    `-NoProfile -WindowStyle Hidden -ExecutionPolicy Bypass -File "${script}"`
  )}
$logon = New-ScheduledTaskTrigger -AtLogOn -User $who
$logon.Delay = 'PT20S'
$repeat = New-ScheduledTaskTrigger -Once -At ((Get-Date).AddMinutes(2)) -RepetitionInterval (New-TimeSpan -Minutes 5) -RepetitionDuration (New-TimeSpan -Days 3650)
$settings = New-ScheduledTaskSettingsSet -AllowStartIfOnBatteries -DontStopIfGoingOnBatteries -StartWhenAvailable -MultipleInstances IgnoreNew -ExecutionTimeLimit (New-TimeSpan -Minutes 2)
Register-ScheduledTask -TaskName ${psQuote(TASK_NAME)} -Action $action -Trigger @($logon, $repeat) -Settings $settings -Force -Description 'Chatbox LAN remote host: starts --serve at logon and restarts it after a crash.' | Out-Null
(Get-ScheduledTask -TaskName ${psQuote(TASK_NAME)}).State
`
  const result = await runPowerShell(['-Command', register], 45_000)
  if (result.code !== 0 || !/Ready|Running/i.test(result.stdout)) {
    log.error('[remote-host] autostart: task registration failed', { code: result.code, stderr: result.stderr })
    return false
  }
  log.info('[remote-host] autostart: scheduled task registered', { task: TASK_NAME, guard: script })
  return true
}

export async function removeServeAutostart(): Promise<boolean> {
  if (process.platform !== 'win32') return false
  const result = await runPowerShell([
    '-Command',
    `Unregister-ScheduledTask -TaskName ${psQuote(TASK_NAME)} -Confirm:$false -ErrorAction SilentlyContinue; 'removed'`,
  ])
  try {
    fs.rmSync(guardPath(), { force: true })
  } catch {
    // ignore
  }
  log.info('[remote-host] autostart: task removed', { code: result.code })
  return result.code === 0
}

export async function isServeAutostartInstalled(): Promise<boolean> {
  if (process.platform !== 'win32') return false
  const result = await runPowerShell([
    '-Command',
    `$task = Get-ScheduledTask -TaskName ${psQuote(TASK_NAME)} -ErrorAction SilentlyContinue; if ($task) { 'yes' } else { 'no' }`,
  ])
  return /yes/i.test(result.stdout)
}
